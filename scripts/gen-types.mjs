#!/usr/bin/env node
// Generates TypeScript types for each product schema from the migrations
// (`pnpm db:types`, needs `pnpm db:local:start`). Every client schema of a product
// has the same shape, so the types are generated from a template schema named after
// the product, and apps use them whatever their own schema is called.
import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { delimiter, join } from "node:path";

const PRODUCTS = ["school", "finance", "clinic"];
const env = {
  ...process.env,
  PATH: [join(process.cwd(), "node_modules", ".bin"), process.env.PATH].join(delimiter),
  SUPABASE_INTERNAL_IMAGE_REGISTRY: process.env.SUPABASE_INTERNAL_IMAGE_REGISTRY ?? "docker.io",
};

function run(command, args) {
  const result = spawnSync(command, args, { env, encoding: "utf8", maxBuffer: 32 * 1024 * 1024 });
  if (result.status !== 0) {
    process.stderr.write(result.stderr ?? "");
    throw new Error(`${command} ${args.join(" ")} failed`);
  }
  return result.stdout;
}

// The template schema is rebuilt every run so edited migrations never leave stale types.
const dropTemplate = (schema) =>
  `import { connect, LOCAL_DATABASE_URL } from "./packages/db/src/index.ts";
   const sql = connect(process.env.DATABASE_URL ?? LOCAL_DATABASE_URL);
   await sql.unsafe("drop schema if exists ${schema} cascade");
   await sql.end();`;

for (const product of PRODUCTS) {
  run("node", ["--input-type=module", "-e", dropTemplate(product)]);
  run("node", [
    "packages/db/src/cli/migrate.ts",
    "--schema",
    product,
    "--product",
    product,
    "--project",
    "local",
  ]);
  const types = run("supabase", ["gen", "types", "typescript", "--local", "--schema", product]);
  const file = join("packages", "db", "types", `${product}.ts`);
  writeFileSync(
    file,
    `// Generated by \`pnpm db:types\` from packages/db migrations. Do not edit.\n${types}`,
  );
  run("prettier", ["--write", file]);
  process.stdout.write(`Wrote ${file}\n`);
}
