"use server";

import { revalidatePath } from "next/cache";
import { redirect } from "next/navigation";
import { z } from "zod";
import { ActionError, must, optionalText, requiredText, runAction, uuid } from "@/lib/action";
import type { FormState } from "@/lib/form-state";
import { personName } from "@/lib/format";
import { REGISTRAR } from "@/lib/roles";
import { createMemberUser } from "@/lib/users";

const optionalDate = z
  .string()
  .optional()
  .transform((v) => (v ? v : null))
  .refine((v) => v === null || /^\d{4}-\d{2}-\d{2}$/.test(v), "Enter a valid date");
const optionalEmail = z
  .string()
  .optional()
  .transform((v) => (v && v.trim() ? v.trim().toLowerCase() : null))
  .refine((v) => v === null || z.email().safeParse(v).success, "Enter a valid email address");
const sex = z
  .string()
  .optional()
  .transform((v) => (v === "female" || v === "male" ? v : null));

const personFields = {
  first_name: requiredText("the first name", 80),
  middle_name: optionalText,
  last_name: requiredText("the last name", 80),
  sex,
  date_of_birth: optionalDate,
  phone: optionalText,
  email: optionalEmail,
  address: optionalText,
};

const admissionSchema = z.object({
  ...personFields,
  program_id: uuid("a program"),
  start_term_id: uuid("the start term"),
  guardian_first_name: optionalText,
  guardian_last_name: optionalText,
  guardian_relationship: optionalText,
  guardian_phone: optionalText,
  confirm_duplicate: z.string().optional(),
});

/** Admission: student, optional guardian and program enrollment (SPEC.md 7.5). */
export async function admitStudent(_previous: FormState, formData: FormData): Promise<FormState> {
  let newId = "";
  const result = await runAction(
    formData,
    { roles: REGISTRAR, schema: admissionSchema },
    async (d, { supabase }) => {
      // Likely duplicate: same name and date of birth (SCH-01). Saving needs a confirmation.
      const duplicates = must(
        await supabase.rpc("find_possible_duplicates", {
          p_first_name: d.first_name,
          p_last_name: d.last_name,
          // Null matches students without a date of birth (the generated type says string).
          p_date_of_birth: d.date_of_birth as string,
        }),
      );
      if (duplicates.length > 0 && d.confirm_duplicate !== "yes") {
        return {
          status: "error",
          message: `A student with this name and date of birth already exists: ${duplicates
            .map((s) => `${personName(s)} (${s.student_number})`)
            .join(", ")}. Check it is not the same person, then confirm below.`,
          data: { duplicates: duplicates.map((s) => s.student_number).join(", ") },
        };
      }
      if ((d.guardian_first_name === null) !== (d.guardian_last_name === null)) {
        return {
          status: "error",
          fieldErrors: { guardian_last_name: "Enter both names of the guardian, or neither" },
        };
      }
      const student = must(
        await supabase
          .from("students")
          .insert({
            // Generated by the database (SCH-01); any value sent is replaced.
            student_number: "",
            first_name: d.first_name,
            middle_name: d.middle_name,
            last_name: d.last_name,
            sex: d.sex,
            date_of_birth: d.date_of_birth,
            phone: d.phone,
            email: d.email,
            address: d.address,
          })
          .select("id, student_number")
          .single(),
      );
      must(
        await supabase.from("program_enrollments").insert({
          student_id: student.id,
          program_id: d.program_id,
          start_term_id: d.start_term_id,
        }),
      );
      if (d.guardian_first_name && d.guardian_last_name) {
        const guardian = must(
          await supabase
            .from("guardians")
            .insert({
              first_name: d.guardian_first_name,
              last_name: d.guardian_last_name,
              relationship: d.guardian_relationship,
              phone: d.guardian_phone,
            })
            .select("id")
            .single(),
        );
        must(
          await supabase
            .from("student_guardians")
            .insert({ student_id: student.id, guardian_id: guardian.id, is_primary: true }),
        );
      }
      newId = student.id;
    },
  );
  if (result.status === "success" && newId) {
    revalidatePath("/students");
    redirect(`/students/${newId}?admitted=1`);
  }
  return result;
}

const updateSchema = z.object({
  id: uuid(),
  ...personFields,
  status: z.enum(["active", "withdrawn", "graduated", "suspended"], { error: "Choose a status" }),
});

export async function updateStudent(_previous: FormState, formData: FormData): Promise<FormState> {
  return runAction(
    formData,
    { roles: REGISTRAR, schema: updateSchema, revalidate: ["/students"] },
    async (d, { supabase }) => {
      const { id, ...fields } = d;
      must(await supabase.from("students").update(fields).eq("id", id));
      return "Student details saved.";
    },
  );
}

const guardianSchema = z.object({
  student_id: uuid(),
  first_name: requiredText("the first name", 80),
  last_name: requiredText("the last name", 80),
  relationship: optionalText,
  phone: optionalText,
  email: optionalEmail,
});

export async function addGuardian(_previous: FormState, formData: FormData): Promise<FormState> {
  return runAction(
    formData,
    { roles: REGISTRAR, schema: guardianSchema, revalidate: ["/students"] },
    async (d, { supabase }) => {
      const { student_id, ...fields } = d;
      const guardian = must(await supabase.from("guardians").insert(fields).select("id").single());
      const existing = must(
        await supabase
          .from("student_guardians")
          .select("guardian_id")
          .eq("student_id", student_id)
          .eq("is_primary", true),
      );
      must(
        await supabase
          .from("student_guardians")
          .insert({ student_id, guardian_id: guardian.id, is_primary: existing.length === 0 }),
      );
      return "Guardian added.";
    },
  );
}

const enrollSchema = z.object({
  student_id: uuid(),
  program_id: uuid("a program"),
  start_term_id: uuid("the start term"),
});

/** Enrolls in a program; an existing active enrollment is marked withdrawn first. */
export async function enrollInProgram(
  _previous: FormState,
  formData: FormData,
): Promise<FormState> {
  return runAction(
    formData,
    { roles: REGISTRAR, schema: enrollSchema, revalidate: ["/students"] },
    async (d, { supabase }) => {
      must(
        await supabase
          .from("program_enrollments")
          .update({ status: "withdrawn" })
          .eq("student_id", d.student_id)
          .eq("status", "active"),
      );
      must(await supabase.from("program_enrollments").insert(d));
      return "Program enrollment saved.";
    },
  );
}

