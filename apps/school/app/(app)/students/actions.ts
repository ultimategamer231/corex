const portalSchema = z.object({
  student_id: uuid(),
  email: z.email("Enter a valid email address").transform((v) => v.toLowerCase()),
});

/** Creates the student's portal sign-in (Super Admin, SPEC.md 5.3 and 7.5). */
export async function createStudentLogin(
  _previous: FormState,
  formData: FormData,
): Promise<FormState> {
  return runAction(
    formData,
    { roles: ["super_admin"], schema: portalSchema, revalidate: ["/students"] },
    async (d, { supabase }) => {
      const student = must(
        await supabase
          .from("students")
          .select("first_name, last_name, user_id")
          .eq("id", d.student_id)
          .single(),
      );
      if (student.user_id) throw new ActionError("This student already has a portal sign-in.");
      const { userId, password } = await createMemberUser(supabase, {
        email: d.email,
        displayName: `${student.first_name} ${student.last_name}`,
        role: "student",
      });
      must(
        await supabase
          .from("students")
          .update({ user_id: userId, email: d.email })
          .eq("id", d.student_id),
      );
      return `Portal sign-in created for ${d.email}. Temporary password: ${password} (shown once; ask the student to change it).`;
    },
  );
}
