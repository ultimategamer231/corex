-- Rank of a student in their section for a term, from locked scores: subject
-- averages Σ(score × weight) ÷ Σ(weight), then their mean. Only the rank is returned,
-- never other students' averages; the student, their parents and the Registrar may ask.
create function {{schema}}.student_rank(p_student_id uuid, p_term_id uuid)
returns table (rank integer, out_of integer)
language sql
stable
security definer
set search_path = ''
as $$
  with placement as (
    select p.section_id
    from {{schema}}.student_placements p
    join {{schema}}.terms t on t.academic_year_id = p.academic_year_id
    where p.student_id = p_student_id and t.id = p_term_id
  ),
  subject_avg as (
    select ps.student_id, round(sum(ps.score * mp.weight) / sum(mp.weight), 2) as average
    from {{schema}}.period_scores ps
    join {{schema}}.marking_periods mp on mp.id = ps.marking_period_id
    join {{schema}}.section_subjects ss on ss.id = ps.section_subject_id
    where mp.term_id = p_term_id and ps.status = 'locked'
      and ss.section_id = (select section_id from placement)
    group by ps.student_id, ps.section_subject_id
  ),
  overall as (
    select student_id, round(avg(average), 2) as average from subject_avg group by student_id
  ),
  ranked as (
    select student_id, rank() over (order by average desc) as r, count(*) over () as n from overall
  )
  select r::integer, n::integer from ranked
  where student_id = p_student_id
    and (p_student_id in (select {{schema}}.my_student_ids()) or {{schema}}.is_registrar());
$$;

grant execute on function {{schema}}.student_rank(uuid, uuid) to authenticated;

-- Promotions -----------------------------------------------------------------------

-- Places students for the next year from the promotion decisions (SPEC.md 7.4):
-- promoted or conditional to the next grade level, repeat to the same one, into the
-- section with the same name (or the first one). Promoted from the top grade level
-- means graduated. Students already placed in the next year are left alone.
create function {{schema}}.apply_promotions(p_from_year_id uuid, p_to_year_id uuid)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v record;
  v_level uuid;
  v_section uuid;
  v_count integer := 0;
begin
  if not {{schema}}.is_registrar() then
    raise exception 'Only the Registrar can apply promotions' using errcode = '42501';
  end if;
  if p_from_year_id = p_to_year_id then
    raise exception 'Choose a different year to place students in' using errcode = '23514';
  end if;
  for v in
    select pr.student_id, pr.decision, s.name as section_name, gl.sort_order
    from {{schema}}.promotions pr
    join {{schema}}.student_placements p on p.student_id = pr.student_id and p.academic_year_id = pr.academic_year_id
    join {{schema}}.sections s on s.id = p.section_id
    join {{schema}}.grade_levels gl on gl.id = s.grade_level_id
    where pr.academic_year_id = p_from_year_id
      and not exists (
        select 1 from {{schema}}.student_placements n
        where n.student_id = pr.student_id and n.academic_year_id = p_to_year_id
      )
  loop
    if v.decision = 'repeat' then
      select id into v_level from {{schema}}.grade_levels where sort_order = v.sort_order;
    else
      select id into v_level from {{schema}}.grade_levels where sort_order > v.sort_order order by sort_order limit 1;
    end if;
    if v_level is null then
      update {{schema}}.students set status = 'graduated' where id = v.student_id;
      continue;
    end if;
    select id into v_section from {{schema}}.sections
    where grade_level_id = v_level and academic_year_id = p_to_year_id
    order by (name = v.section_name) desc, name
    limit 1;
    if v_section is null then
      raise exception 'Add sections for every grade level in the new year first' using errcode = '23514';
    end if;
    insert into {{schema}}.student_placements (student_id, section_id, academic_year_id)
    values (v.student_id, v_section, p_to_year_id);
    v_count := v_count + 1;
    v_level := null;
  end loop;
  return v_count;
end;
$$;

grant execute on function {{schema}}.apply_promotions(uuid, uuid) to authenticated;

-- Fees: High School students are invoiced by grade level ------------------------------

-- Replaces the College-only version: a student's fee group is their program code
-- (College) or their grade level name in the term's year (High School).
create or replace function {{schema}}.generate_term_invoices(p_term_id uuid, p_due_date date default null)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_term {{schema}}.terms%rowtype;
  v_target record;
  v_invoice uuid;
  v_count integer := 0;
begin
  if not {{schema}}.can_bill() then
    raise exception 'Only the Bursar can generate fee invoices' using errcode = '42501';
  end if;
  select * into v_term from {{schema}}.terms where id = p_term_id;
  if not found then
    raise exception 'Term not found' using errcode = 'P0002';
  end if;
  for v_target in
    with fee_groups as (
      select e.student_id, p.code as fee_group
      from {{schema}}.program_enrollments e
      join {{schema}}.programs p on p.id = e.program_id
      where e.status = 'active'
      union
      select pl.student_id, gl.name
      from {{schema}}.student_placements pl
      join {{schema}}.sections sc on sc.id = pl.section_id
      join {{schema}}.grade_levels gl on gl.id = sc.grade_level_id
      where pl.academic_year_id = v_term.academic_year_id
    )
    select s.id as student_id, f.currency, array_agg(distinct g.fee_group) as fee_groups
    from {{schema}}.students s
    join fee_groups g on g.student_id = s.id
    join {{schema}}.fee_structures f
      on f.academic_year_id = v_term.academic_year_id
     and (f.term_id is null or f.term_id = p_term_id)
     and (f.applies_to = 'all' or f.applies_to = g.fee_group)
    where s.status = 'active'
      and not exists (
        select 1 from {{schema}}.term_invoices ti
        where ti.term_id = p_term_id and ti.student_id = s.id and ti.currency = f.currency
      )
    group by s.id, f.currency
  loop
    insert into {{schema}}.invoices (party_type, party_id, currency, due_date, notes)
    values ('student', v_target.student_id, v_target.currency, p_due_date, v_term.name || ' fees')
    returning id into v_invoice;
    insert into {{schema}}.invoice_lines (invoice_id, description, quantity, unit_amount_minor, amount_minor)
    select v_invoice, f.item, 1, f.amount_minor, f.amount_minor
    from {{schema}}.fee_structures f
    where f.academic_year_id = v_term.academic_year_id
      and (f.term_id is null or f.term_id = p_term_id)
      and (f.applies_to = 'all' or f.applies_to = any (v_target.fee_groups))
      and f.currency = v_target.currency
    order by f.item;
    perform {{schema}}.issue_invoice(v_invoice);
    insert into {{schema}}.term_invoices (term_id, student_id, currency, invoice_id)
    values (p_term_id, v_target.student_id, v_target.currency, v_invoice);
    v_count := v_count + 1;
  end loop;
  return v_count;
end;
$$;

