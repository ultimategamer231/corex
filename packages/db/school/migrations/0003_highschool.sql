-- Period scores: the assigned teacher only, students placed in the section in the
-- marking period's year, and only while the score is a draft (SCH-02, SCH-03).
create function {{schema}}.period_scores_guard()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_row {{schema}}.period_scores%rowtype := coalesce(new, old);
  v_section uuid;
  v_ok boolean;
begin
  if tg_op = 'DELETE' then
    raise exception 'Scores are never deleted' using errcode = '23514';
  end if;
  -- Status changes come only from the approval functions, which run without these checks.
  if coalesce(current_setting('corex.grade_workflow', true), '') = 'on' then
    return new;
  end if;
  if (select auth.uid()) is not null and not {{schema}}.teaches_section_subject(v_row.section_subject_id) then
    raise exception 'You are not assigned to this subject' using errcode = '42501';
  end if;
  if tg_op = 'UPDATE' then
    if old.status <> 'draft' then
      raise exception 'This score is %; it cannot be changed', old.status using errcode = '23514';
    end if;
    if (new.student_id, new.section_subject_id, new.marking_period_id, new.status)
       is distinct from (old.student_id, old.section_subject_id, old.marking_period_id, old.status) then
      raise exception 'Only the score itself can be changed' using errcode = '23514';
    end if;
    return new;
  end if;
  if new.status <> 'draft' then
    raise exception 'New scores start as drafts' using errcode = '23514';
  end if;
  select ss.section_id into v_section from {{schema}}.section_subjects ss where ss.id = new.section_subject_id;
  select exists (
    select 1
    from {{schema}}.student_placements p
    join {{schema}}.marking_periods mp on mp.id = new.marking_period_id
    join {{schema}}.terms t on t.id = mp.term_id
    where p.section_id = v_section and p.student_id = new.student_id and p.academic_year_id = t.academic_year_id
  ) into v_ok;
  if not v_ok then
    raise exception 'The student is not in this section for that marking period' using errcode = '23514';
  end if;
  return new;
end;
$$;

revoke execute on function {{schema}}.period_scores_guard() from authenticated;

create trigger period_scores_guard
  before insert or update or delete on {{schema}}.period_scores
  for each row execute function {{schema}}.period_scores_guard();

-- Approve and lock flow per section subject and marking period -----------------------

-- Teacher (or Registrar) submits once every student in the section has a score.
create function {{schema}}.submit_period_scores(p_section_subject_id uuid, p_marking_period_id uuid)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_missing integer;
  v_count integer;
begin
  if not ({{schema}}.teaches_section_subject(p_section_subject_id) or {{schema}}.is_registrar()) then
    raise exception 'Only the assigned teacher can submit these scores' using errcode = '42501';
  end if;
  select count(*) into v_missing
  from {{schema}}.section_subjects ss
  join {{schema}}.student_placements p on p.section_id = ss.section_id
  join {{schema}}.marking_periods mp on mp.id = p_marking_period_id
  join {{schema}}.terms t on t.id = mp.term_id and t.academic_year_id = p.academic_year_id
  left join {{schema}}.period_scores ps
    on ps.student_id = p.student_id and ps.section_subject_id = ss.id and ps.marking_period_id = mp.id
  where ss.id = p_section_subject_id and ps.id is null;
  if v_missing > 0 then
    raise exception '% scores are still missing', v_missing using errcode = '23514';
  end if;
  perform set_config('corex.grade_workflow', 'on', true);
  update {{schema}}.period_scores set status = 'submitted', submitted_at = now()
  where section_subject_id = p_section_subject_id and marking_period_id = p_marking_period_id and status = 'draft';
  get diagnostics v_count = row_count;
  perform set_config('corex.grade_workflow', '', true);
  if v_count = 0 then
    raise exception 'There are no draft scores to submit' using errcode = '23514';
  end if;
  return v_count;
end;
$$;

-- Registrar approves; a teacher never approves their own scores.
