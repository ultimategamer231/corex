  where section_subject_id = p_section_subject_id and marking_period_id = p_marking_period_id and status = 'submitted';
  get diagnostics v_count = row_count;
  perform set_config('corex.grade_workflow', '', true);
  if v_count = 0 then
    raise exception 'There are no submitted scores to approve' using errcode = '23514';
  end if;
  return v_count;
end;
$$;

