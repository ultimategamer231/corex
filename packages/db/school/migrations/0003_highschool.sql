create policy students_teacher_read on {{schema}}.students
  for select to authenticated
  using (id in (
    select p.student_id from {{schema}}.student_placements p
    where p.section_id in (select {{schema}}.my_section_ids())
  ));

-- Daily attendance per section by the homeroom teacher or the Registrar (SCH-02).
create policy attendance_section_teacher_read on {{schema}}.attendance
  for select to authenticated
  using (class_ref_type = 'section' and class_ref_id in (select {{schema}}.my_section_ids()));
create policy attendance_section_insert on {{schema}}.attendance
  for insert to authenticated
  with check (
    class_ref_type = 'section'
    and ({{schema}}.is_homeroom_teacher(class_ref_id) or (select {{schema}}.is_registrar()))
    and {{schema}}.in_section(class_ref_id, student_id)
    and recorded_by = (select auth.uid())
  );

