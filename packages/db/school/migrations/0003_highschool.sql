-- High School edition (SPEC.md 7.4): grade levels, sections, subjects, placements,
-- marking periods, period scores with the approve and lock flow, and promotions.
-- Teachers act only on their assigned section subjects (SCH-02); students and
-- parents see only locked scores of their own (SCH-07).

create table {{schema}}.grade_levels (
  id uuid primary key default gen_random_uuid(),
  name text not null unique check (length(trim(name)) > 0),
  -- SPEC's `order`; renamed because ORDER is an SQL keyword (D27).
  sort_order integer not null unique check (sort_order >= 0),
  created_at timestamptz not null default now()
);

create table {{schema}}.sections (
  id uuid primary key default gen_random_uuid(),
  grade_level_id uuid not null references {{schema}}.grade_levels (id),
  academic_year_id uuid not null references {{schema}}.academic_years (id),
  name text not null check (length(trim(name)) > 0),
  -- The homeroom teacher's auth user (D21).
  homeroom_teacher_id uuid references auth.users (id),
  created_at timestamptz not null default now(),
  unique (grade_level_id, academic_year_id, name)
);

create table {{schema}}.subjects (
  id uuid primary key default gen_random_uuid(),
  name text not null unique check (length(trim(name)) > 0),
  code text not null unique check (code ~ '^[A-Z0-9]{2,8}$'),
  created_at timestamptz not null default now()
);

create table {{schema}}.section_subjects (
  id uuid primary key default gen_random_uuid(),
  section_id uuid not null references {{schema}}.sections (id),
  subject_id uuid not null references {{schema}}.subjects (id),
  teacher_id uuid references auth.users (id),
  created_at timestamptz not null default now(),
  unique (section_id, subject_id)
);
create index section_subjects_teacher_idx on {{schema}}.section_subjects (teacher_id);

create table {{schema}}.student_placements (
  id uuid primary key default gen_random_uuid(),
  student_id uuid not null references {{schema}}.students (id),
  section_id uuid not null references {{schema}}.sections (id),
  academic_year_id uuid not null references {{schema}}.academic_years (id),
  created_at timestamptz not null default now(),
  -- One placement per student per year.
  unique (student_id, academic_year_id)
);
create index student_placements_section_idx on {{schema}}.student_placements (section_id);

create table {{schema}}.marking_periods (
  id uuid primary key default gen_random_uuid(),
  term_id uuid not null references {{schema}}.terms (id),
  number integer not null check (number >= 1),
  name text not null check (length(trim(name)) > 0),
  is_exam boolean not null default false,
  weight numeric(5, 2) not null default 1 check (weight > 0),
  created_at timestamptz not null default now(),
  unique (term_id, number)
);

create table {{schema}}.period_scores (
  -- Generated by the device so offline entries sync once (CORE-06).
  id uuid primary key,
  student_id uuid not null references {{schema}}.students (id),
  section_subject_id uuid not null references {{schema}}.section_subjects (id),
  marking_period_id uuid not null references {{schema}}.marking_periods (id),
  score numeric(5, 2) not null check (score between 0 and 100),
  status text not null default 'draft' check (status in ('draft', 'submitted', 'approved', 'locked')),
  entered_by uuid default auth.uid(),
  submitted_at timestamptz,
  approved_by uuid,
  approved_at timestamptz,
  locked_at timestamptz,
  created_at timestamptz not null default now(),
  unique (student_id, section_subject_id, marking_period_id)
);
create index period_scores_class_idx on {{schema}}.period_scores (section_subject_id, marking_period_id);

create table {{schema}}.promotions (
  id uuid primary key default gen_random_uuid(),
  student_id uuid not null references {{schema}}.students (id),
  academic_year_id uuid not null references {{schema}}.academic_years (id),
  decision text not null check (decision in ('promoted', 'repeat', 'conditional')),
  decided_by uuid default auth.uid(),
  note text,
  created_at timestamptz not null default now(),
  unique (student_id, academic_year_id)
);

